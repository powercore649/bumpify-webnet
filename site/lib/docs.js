export function getNeighbors(slug) {
  const idx = DOCS.findIndex(d => d.slug === slug);
  return {
    prev: idx > 0 ? DOCS[idx - 1] : null,
    next: idx >= 0 && idx < DOCS.length - 1 ? DOCS[idx + 1] : null,
  };
}
